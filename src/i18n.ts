const resources = {
  en: { translation: en },
  fr: { translation: fr },
  ar: { translation: ar },
  es: { translation: es },
};

const savedLang = typeof window !== 'undefined' ? localStorage.getItem('__lang') : null;

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: savedLang || 'en',
    fallbackLng: 'en',
    interpolation: { escapeValue: false }
  });

export function setLanguage(lng: string) {
  i18n.changeLanguage(lng);
  if (typeof window !== 'undefined') {
    localStorage.setItem('__lang', lng);
    document.documentElement.dir = lng === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lng;
  }
}

// Initialize RTL on load
if (typeof window !== 'undefined') {
  const currentLng = savedLang || 'en';
  document.documentElement.dir = currentLng === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = currentLng;
}

